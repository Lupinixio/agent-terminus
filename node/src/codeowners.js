// CODEOWNERS block for every protected path, and its freshness check.
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { protectedGlobs } from './index-file.js';

/** @typedef {import('./types.js').Project} Project */

export const BEGIN = '# BEGIN boundaries-kit';
export const END = '# END boundaries-kit';
export const DEFAULT_OWNER = '@your-org/boundary-owners';
export const CODEOWNERS_LOCATIONS = Object.freeze(['.github/CODEOWNERS', 'CODEOWNERS', 'docs/CODEOWNERS']);

/**
 * Glob to CODEOWNERS pattern: `x/**` becomes `/x/`, anything else `/` + glob.
 * @param {string} glob
 */
export function toCodeownersPattern(glob) {
  if (glob.endsWith('/**') && !glob.slice(0, -3).includes('*')) return `/${glob.slice(0, -3)}/`;
  return `/${glob}`;
}

/**
 * Whether a CODEOWNERS pattern (as produced above) covers a protected glob.
 * Patterns are compared after conversion; a directory pattern covers every
 * glob below it.
 * @param {string} pattern
 * @param {string} glob
 */
export function patternCovers(pattern, glob) {
  const wanted = toCodeownersPattern(glob);
  if (pattern === wanted) return true;
  if (pattern.endsWith('/') && !pattern.includes('*')) {
    return wanted.startsWith(pattern);
  }
  return false;
}

/**
 * @param {Project} project
 * @param {string} [owner]
 */
export function codeownersBlock(project, owner = DEFAULT_OWNER) {
  const lines = protectedGlobs(project).map((g) => `${toCodeownersPattern(g)} ${owner}`);
  return [BEGIN, '# Generated by `boundaries codeowners`. Paths that enforce the project limits.', ...lines, END, ''].join('\n');
}

/**
 * Patterns inside the marker block of a CODEOWNERS text, or null without markers.
 * @param {string} text
 * @returns {string[] | null}
 */
export function blockPatterns(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const start = lines.findIndex((l) => l.trim() === BEGIN);
  const end = lines.findIndex((l, i) => i > start && l.trim() === END);
  if (start === -1 || end === -1) return null;
  return lines
    .slice(start + 1, end)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => l.split(/\s+/)[0]);
}

/**
 * Protected globs missing from the marker block of the project's CODEOWNERS.
 * Returns null when no CODEOWNERS file carries the markers.
 * @param {Project} project
 * @returns {{ file: string, missing: string[] } | null}
 */
export function codeownersGaps(project) {
  for (const rel of CODEOWNERS_LOCATIONS) {
    const abs = path.join(project.root, rel);
    if (!existsSync(abs)) continue;
    const patterns = blockPatterns(readFileSync(abs, 'utf8'));
    if (patterns === null) continue;
    const missing = protectedGlobs(project).filter((g) => !patterns.some((p) => patternCovers(p, g)));
    return { file: rel, missing };
  }
  return null;
}
